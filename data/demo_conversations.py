def get_demo_conversations(start: int = 0, end: int = None) -> list:
    """获取演示对话的子集"""
    if end is None:
        end = len(DEMO_CONVERSATIONS)
    return DEMO_CONVERSATIONS[start:end]


def print_conversation_stats():
    """打印对话统计信息"""
    print(f"总对话轮数: {len(DEMO_CONVERSATIONS)}")
    print(f"用户消息数: {sum(1 for c in DEMO_CONVERSATIONS if c['role'] == 'user')}")
    print(f"助手消息数: {sum(1 for c in DEMO_CONVERSATIONS if c['role'] == 'assistant')}")

    # 统计各类信息
    content = " ".join([c["content"] for c in DEMO_CONVERSATIONS])
    keywords = ["投诉", "套餐", "宽带", "增值业务", "副卡", "转网", "信号", "发票", "缴费"]
    print("\n关键词统计:")
    for kw in keywords:
        count = content.count(kw)
        print(f"  {kw}: {count} 次")


if __name__ == "__main__":
    print_conversation_stats()
